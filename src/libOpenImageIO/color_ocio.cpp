bool
fileTransformIsBlockable(const ConstFileTransformRcPtr& fileTransform)
{
    if (!fileTransform) {
        return true;
    }
    const char* src = fileTransform->getSrc();
    if (!src || !*src) {
        return true;
    }
    if (Strutil::iends_with(src, ".spi1d")
        || Strutil::iends_with(src, ".spimtx")) {
        return false;
    }
    return true;
}

