static OCIO::ConstContextRcPtr
make_context_with_overrides(
    const OCIO::ConstConfigRcPtr& config,
    const std::map<std::string, std::string>& context_vars)
{
    if (!config)
        return nullptr;
    OCIO::ConstContextRcPtr context = config->getCurrentContext();
    if (!context_vars.empty()) {
        OCIO::ContextRcPtr ctx = context->createEditableCopy();
        for (const auto& kv : context_vars) {
            ctx->setStringVar(kv.first.c_str(), kv.second.c_str());
        }
        context = ctx;
    }
    return context;
}

// Build fingerprint cache key from config+context cache identities.
static std::string
fingerprint_cache_key(const ConstConfigRcPtr& config,
                      const ConstContextRcPtr& context)
{
    if (!config)
        return "";
    ConstContextRcPtr ctx = context ? context : config->getCurrentContext();
    const std::string config_id = config->getCacheID();
    const std::string ctx_id    = ctx ? ctx->getCacheID() : std::string();
    // Example key: "ctx:abc123@cfg:deadbeef"
    return Strutil::fmt::format("{}@{}", ctx_id, config_id);
}

// Return cached fingerprints for a config/context, initializing on miss.
FingerprintCacheEntry
get_fingerprint_cache_entry(const ConstConfigRcPtr& config,
                            const ConstContextRcPtr& context,
                            const FingerprintRuntime& runtime)
{
    FingerprintCacheEntry entry;
    if (!config)
        return entry;

    const std::string cacheID = fingerprint_cache_key(config, context);
    {
        std::lock_guard<std::mutex> lock(runtime.cache_mutex);
        auto it = runtime.cache.find(cacheID);
        if (it != runtime.cache.end())
            return it->second;
    }

    Timer timer;
    ConstContextRcPtr ctx = context ? context : config->getCurrentContext();
    initializeTestVals(entry.fingerprints, config);
    initializeColorSpaceFingerprints(entry.fingerprints, entry.by_name, config,
                                     ctx, runtime.source_colorspace);
    entry.seconds += timer.lap();

    {
        std::lock_guard<std::mutex> lock(runtime.cache_mutex);
        runtime.cache.emplace(cacheID, entry);
    }

    return entry;
}

// Try to retrieve one colorspace fingerprint from cache by name/type.
bool
get_cached_fingerprint_for_colorspace(const ConstConfigRcPtr& config,
                                      const ConstColorSpaceRcPtr& cs,
                                      const ConstContextRcPtr& context,
                                      ColorSpaceFingerprints& fingerprints,
                                      std::vector<float>& fingerprintVals,
                                      const FingerprintRuntime& runtime)
{
    if (!config || !cs)
        return false;

    const std::string cacheID = fingerprint_cache_key(config, context);
    {
        std::lock_guard<std::mutex> lock(runtime.cache_mutex);
        auto it = runtime.cache.find(cacheID);
        if (it != runtime.cache.end()) {
            auto found = it->second.by_name.find(cs->getName());
            if (found != it->second.by_name.end()
                && found->second.type == cs->getReferenceSpaceType()) {
                fingerprintVals = found->second.vals;
                return true;
            }
            fingerprints = it->second.fingerprints;
        }
    }

    // Ensure fingerprints are initialized for this config if not already cached.
    FingerprintCacheEntry entry = get_fingerprint_cache_entry(config, context,
                                                              runtime);
    fingerprints                = entry.fingerprints;
    auto found                  = entry.by_name.find(cs->getName());
    if (found != entry.by_name.end()
        && found->second.type == cs->getReferenceSpaceType()) {
        fingerprintVals = found->second.vals;
        return true;
    }

    return false;
}

// Compute one colorspace fingerprint and publish it into the cache.
std::vector<float>
helper_get_colorspace_fingerprint(const ConstConfigRcPtr& config,
                                  string_view colorspace,
                                  const ConstContextRcPtr& context,
                                  const FingerprintRuntime& runtime)
{
    std::vector<float> inputVals;
    if (!config || colorspace.empty())
        return inputVals;

    ConstColorSpaceRcPtr cs = config->getColorSpace(c_str(colorspace));
    if (!cs || cs->isData())
        return inputVals;

    ConstContextRcPtr ctx = context ? context : config->getCurrentContext();
    ColorSpaceFingerprints fingerprints;
    bool have_cached
        = get_cached_fingerprint_for_colorspace(config, cs, ctx, fingerprints,
                                                inputVals, runtime);
    if (have_cached)
        return inputVals;

    Timer timer;
    const bool skipColorSpace
        = calcColorSpaceFingerprint(inputVals, fingerprints, config, cs, ctx,
                                    runtime.source_colorspace);
    if (skipColorSpace || inputVals.empty())
        return std::vector<float>();

    Fingerprint fprint;
    fprint.csName = cs->getName();
    fprint.type   = cs->getReferenceSpaceType();
    fprint.vals   = inputVals;

    const std::string cacheID = fingerprint_cache_key(config, ctx);
    {
        std::lock_guard<std::mutex> lock(runtime.cache_mutex);
        auto it = runtime.cache.find(cacheID);
        if (it != runtime.cache.end()) {
            if (!it->second.by_name.count(fprint.csName)) {
                it->second.by_name.emplace(fprint.csName, fprint);
                it->second.fingerprints.vec.push_back(fprint);
                it->second.seconds += timer.lap();
            }
        } else {
            FingerprintCacheEntry entry;
            entry.fingerprints = fingerprints;
            entry.by_name.emplace(fprint.csName, fprint);
            entry.fingerprints.vec.push_back(fprint);
            entry.seconds = timer.lap();
            runtime.cache.emplace(cacheID, entry);
        }
    }

    return inputVals;
}

// Return the first matching colorspace for the given reference-space type.
std::string
find_colorspace_from_fingerprint(const ConstConfigRcPtr& config,
                                 cspan<const float> fingerprint,
                                 ReferenceSpaceType refSpaceType,
                                 const ConstContextRcPtr& context,
                                 const FingerprintRuntime& runtime)
{
    const auto matches = find_colorspace_matches_from_fingerprint(
        config, fingerprint, true, refSpaceType, FingerprintSearchMode::First,
        false, context, runtime);
    return matches.empty() ? std::string() : matches.front();
}

std::vector<std::string>
find_colorspace_matches_from_fingerprint(
    const ConstConfigRcPtr& config, cspan<const float> fingerprint,
    bool filter_ref_space, ReferenceSpaceType refSpaceType,
    FingerprintSearchMode match_mode, bool exhaustive,
    const ConstContextRcPtr& context, const FingerprintRuntime& runtime)
{
    std::vector<std::string> matches;
    if (!config || fingerprint.empty())
        return matches;

    const float absTolerance = kFingerprintAbsTolerance;
    const size_t n           = fingerprint.size();

    float best_max_abs_err = std::numeric_limits<float>::max();
    std::string best_name;

    auto evaluate = [&](string_view name, ReferenceSpaceType type,
                        cspan<const float> vals) -> bool {
        if (filter_ref_space && type != refSpaceType)
            return false;
        if (vals.size() != n)
            return false;

        float max_abs_err = 0.0f;
        bool in_tolerance = true;
        for (size_t i = 0; i < n; ++i) {
            const float abs_err = std::abs(vals[i] - fingerprint[i]);
            max_abs_err         = std::max(max_abs_err, abs_err);
            if (abs_err > absTolerance)
                in_tolerance = false;
        }

        if (match_mode == FingerprintSearchMode::Best) {
            if (max_abs_err < best_max_abs_err) {
                best_max_abs_err = max_abs_err;
                best_name        = std::string(name);
            }
            return false;
        }

        if (!in_tolerance)
            return false;

        if (match_mode == FingerprintSearchMode::First) {
            matches = { std::string(name) };
            return true;
        }

        matches.emplace_back(name);
        return false;
    };

    if (exhaustive) {
        for (int i = 0, e = config->getNumColorSpaces(); i < e; ++i) {
            const char* csname = config->getColorSpaceNameByIndex(i);
            if (!csname || !*csname)
                continue;
            ConstColorSpaceRcPtr cs = config->getColorSpace(csname);
            if (!cs || cs->isData())
                continue;
            auto vals = helper_get_colorspace_fingerprint(config, cs->getName(),
                                                          context, runtime);
            if (vals.empty())
                continue;
            if (evaluate(cs->getName(), cs->getReferenceSpaceType(),
                         cspan<const float>(vals)))
                return matches;
        }
    } else {
        FingerprintCacheEntry entry
            = get_fingerprint_cache_entry(config, context, runtime);
        for (const auto& fp : entry.fingerprints.vec) {
            if (evaluate(fp.csName, fp.type, cspan<const float>(fp.vals)))
                return matches;
        }
    }

    if (match_mode == FingerprintSearchMode::Best && !best_name.empty())
        return { best_name };

    return matches;
}

InteropFingerprintMatcher::InteropFingerprintMatcher(const ConstConfigRcPtr& baseConfig,
                                             FingerprintCacheMap& cache,
                                             std::mutex& cache_mutex)
    : m_cache(&cache)
    , m_cache_mutex(&cache_mutex)
{
    const FingerprintRuntime runtime {
        cache, cache_mutex, std::string(OCIO::ROLE_INTERCHANGE_SCENE)
    };
    FingerprintCacheEntry entry = get_fingerprint_cache_entry(
        baseConfig, baseConfig ? baseConfig->getCurrentContext() : nullptr,
        runtime);
    m_base_fingerprints = entry.fingerprints;
}

std::string
InteropFingerprintMatcher::findEquivalentColorspace(
    const ConstConfigRcPtr& inputConfig, string_view csName,
    const ConstContextRcPtr& context, string_view source_colorspace) const
{
    const auto matches = findEquivalentColorspaces(inputConfig, csName, context,
                                                   source_colorspace);
    return matches.empty() ? std::string() : matches.front();
}

std::vector<std::string>
InteropFingerprintMatcher::findEquivalentColorspaces(
    const ConstConfigRcPtr& inputConfig, string_view csName,
    const ConstContextRcPtr& context, string_view source_colorspace) const
{
    if (!inputConfig || csName.empty())
        return {};

    ConstContextRcPtr ctx   = context ? context
                                      : inputConfig->getCurrentContext();
    csName                  = ctx->resolveStringVar(c_str(csName));
    ConstColorSpaceRcPtr cs = inputConfig->getColorSpace(c_str(csName));

    if (!cs || cs->isData())
        return {};

    std::vector<float> inputVals;
    ColorSpaceFingerprints input_fingerprints;
    bool have_cached = get_cached_fingerprint_for_colorspace(
        inputConfig, cs, ctx, input_fingerprints, inputVals,
        FingerprintRuntime { *m_cache, *m_cache_mutex,
                             std::string(source_colorspace) });

    if (!have_cached) {
        Timer timer;
        const bool skipColorSpace
            = calcColorSpaceFingerprint(inputVals, input_fingerprints,
                                        inputConfig, cs, ctx,
                                        source_colorspace);
        if (skipColorSpace || inputVals.empty())
            return {};

        Fingerprint fprint;
        fprint.csName = cs->getName();
        fprint.type   = cs->getReferenceSpaceType();
        fprint.vals   = inputVals;

        const std::string cacheID = fingerprint_cache_key(inputConfig, ctx);
        {
            std::lock_guard<std::mutex> lock(*m_cache_mutex);
            auto it = m_cache->find(cacheID);
            if (it != m_cache->end()) {
                if (!it->second.by_name.count(fprint.csName)) {
                    it->second.by_name.emplace(fprint.csName, fprint);
                    it->second.fingerprints.vec.push_back(fprint);
                    it->second.seconds += timer.lap();
                }
            }
        }
    }

    if (inputVals.empty())
        return {};

    return findEquivalentColorspacesFromFingerprint(inputVals,
                                                    cs->getReferenceSpaceType());
}

std::string
InteropFingerprintMatcher::findEquivalentColorspaceFromFingerprint(
    const std::vector<float>& inputVals, ReferenceSpaceType refSpaceType) const
{
    const auto matches = findEquivalentColorspacesFromFingerprint(inputVals,
                                                                  refSpaceType);
    return matches.empty() ? std::string() : matches.front();
}

std::vector<std::string>
InteropFingerprintMatcher::findEquivalentColorspacesFromFingerprint(
    const std::vector<float>& inputVals, ReferenceSpaceType refSpaceType) const
{
    std::vector<std::string> matches;
    const float absTolerance = kFingerprintAbsTolerance;
    const size_t n           = inputVals.size();
    for (const auto& fp : m_base_fingerprints.vec) {
        if (fp.type != refSpaceType)
            continue;
        if (fp.vals.size() != n)
            continue;

        bool match = true;
        for (size_t i = 0; i < n; ++i) {
            if (std::abs(fp.vals[i] - inputVals[i]) > absTolerance) {
                match = false;
                break;
            }
        }
        if (match)
            matches.emplace_back(fp.csName);
    }
    return matches;
}

